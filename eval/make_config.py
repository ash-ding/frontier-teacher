"""Derive a config for one checkpoint from the model's benchmark config.

A checkpoint sweep evaluates the same benchmark against 4 sets of weights, and
`--config <base> --model <ckpt>` is refused: a config and the command line are
two ways to describe one run, not layers. So the run gets its own config, which
also leaves a record on disk of exactly what was evaluated.

Only `model` changes. Sampling, verifier, data and caps come from the base
unaltered, which is the point - a checkpoint must be measured the same way its
baseline was, or the comparison is between harnesses rather than models.

  python eval/make_config.py --base configs/eval/llama32-3b__aime.yaml \\
      --model .local_checkpoints/<exp>/global_step_20/actor/huggingface \\
      --out /tmp/run/cfg.yaml
"""
import argparse
from pathlib import Path

import yaml

ap = argparse.ArgumentParser()
ap.add_argument("--base", required=True, help="configs/eval/<model>__<benchmark>.yaml")
ap.add_argument("--model", required=True, help="checkpoint directory to evaluate")
ap.add_argument("--out", required=True)
ap.add_argument("--model-label", default=None,
                help="short name for the output tag; default: the experiment and "
                     "step read out of the checkpoint path")
a = ap.parse_args()

cfg = yaml.safe_load(open(a.base))
cfg["model"] = a.model

label = a.model_label
if label is None:
    parts = Path(a.model).expanduser().parts
    step = next((p for p in reversed(parts) if p.startswith("global_step_")), None)
    label = (f"{parts[parts.index(step) - 1]}__step{step.rsplit('_', 1)[1]}"
             if step else Path(a.model).name)
cfg["model_label"] = label

out = Path(a.out)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("# Generated by eval/make_config.py from " + a.base + "\n"
               "# Only `model` and `model_label` differ from the base; everything\n"
               "# that decides how the score is computed is carried over unchanged.\n"
               + yaml.safe_dump(cfg, sort_keys=False))
print(f"{out}  model_label={label}")
